//! Build-time syntax highlighting with syntect and bat's grammar and theme collection (two-face). Code is emitted
//! with CSS classes, so the colours live in one stylesheet and the pages stay small; `css()` makes that stylesheet.

use std::sync::OnceLock;
use syntect::highlighting::ThemeSet;
use syntect::html::{ClassStyle, ClassedHTMLGenerator, css_for_theme_with_class_style};
use syntect::parsing::SyntaxSet;
use syntect::util::LinesWithEndings;

fn syntaxes() -> &'static SyntaxSet {
    static SET: OnceLock<SyntaxSet> = OnceLock::new();
    SET.get_or_init(two_face::syntax::extra_newlines)
}

fn themes() -> &'static ThemeSet {
    static SET: OnceLock<ThemeSet> = OnceLock::new();
    SET.get_or_init(|| ThemeSet::from(two_face::theme::extra()))
}

pub fn theme_names() -> Vec<&'static str> {
    themes().themes.keys().map(String::as_str).collect()
}

fn class_style(prefix: &str) -> ClassStyle {
    // syntect wants a 'static prefix; prefixes are few and fixed per run, so leaking them is fine.
    static PREFIXES: OnceLock<std::sync::Mutex<Vec<&'static str>>> = OnceLock::new();
    let mut known = PREFIXES.get_or_init(Default::default).lock().unwrap();
    let p = match known.iter().find(|p| **p == prefix) {
        Some(p) => *p,
        None => {
            let p: &'static str = Box::leak(prefix.to_string().into_boxed_str());
            known.push(p);
            p
        }
    };
    if p.is_empty() { ClassStyle::Spaced } else { ClassStyle::SpacedPrefixed { prefix: p } }
}

/// Aliases for fence names that the grammars know under another name.
fn alias(lang: &str) -> &str {
    match lang {
        "sh" | "shell" | "zsh" | "console" => "bash",
        "js" | "mjs" | "cjs" => "javascript",
        "ts" | "mts" => "typescript",
        "yml" => "yaml",
        "rs" => "rust",
        "py" => "python",
        "md" => "markdown",
        "ini" | "conf" => "ini",
        "html" | "xml" | "svg" => lang,
        "jsonc" | "json5" => "json",
        "dockerfile" => "Dockerfile",
        "cs" | "csharp" => "C#",
        "cpp" | "c++" => "C++",
        other => other,
    }
}

/// `<pre><code class="language-x">…</code></pre>` with highlighted tokens, or `None` if the language is unknown.
pub fn highlight(code: &str, lang: &str, prefix: &str) -> Option<String> {
    let set = syntaxes();
    let lang = alias(lang.trim());
    let syntax = set
        .find_syntax_by_token(lang)
        .or_else(|| set.find_syntax_by_name(lang))
        .or_else(|| set.find_syntax_by_extension(lang))?;
    let mut html = ClassedHTMLGenerator::new_with_class_style(syntax, set, class_style(prefix));
    for line in LinesWithEndings::from(code) {
        html.parse_html_for_line_which_includes_newline(line).ok()?;
    }
    let lang_class = crate::util::escape_xml(lang);
    Some(format!(
        "<pre class=\"{prefix}code\"><code class=\"language-{lang_class}\">{}</code></pre>\n",
        html.finalize()
    ))
}

/// The stylesheet for highlighted code: `theme` for everything, `light` (if any) scoped under `light_selector`.
pub fn css(prefix: &str, theme: &str, light: Option<&str>, light_selector: &str) -> anyhow::Result<String> {
    let get = |name: &str| {
        themes().themes.get(name).ok_or_else(|| {
            anyhow::anyhow!("unknown highlight theme {name:?}; `ombryt themes` lists the available ones")
        })
    };
    let mut out = String::from("/* Generated by ombryt from the highlight settings in ombryt.toml. */\n");
    out += &css_for_theme_with_class_style(get(theme)?, class_style(prefix))?;
    if let Some(light) = light {
        let scoped = css_for_theme_with_class_style(get(light)?, class_style(prefix))?;
        out += &scope_css(&scoped, light_selector);
    }
    Ok(out)
}

/// Scopes a flat stylesheet (as syntect writes them): an at-rule such as `@media (prefers-color-scheme: light)`
/// wraps it, a selector such as `[data-theme=light]` is put in front of every selector.
fn scope_css(css: &str, scope: &str) -> String {
    if scope.trim_start().starts_with('@') {
        return format!("\n{} {{\n{css}\n}}\n", scope.trim());
    }
    let mut out = String::with_capacity(css.len() * 2);
    let mut rest = css;
    while let Some(open) = rest.find('{') {
        let Some(close) = rest[open..].find('}').map(|c| open + c) else { break };
        let (selectors, body) = (&rest[..open], &rest[open..=close]);
        let mut comment_free = selectors;
        // Keep comments as they are; scope only what follows them.
        if let Some(end) = selectors.rfind("*/") {
            out += &selectors[..end + 2];
            comment_free = &selectors[end + 2..];
        }
        let scoped: Vec<String> =
            comment_free.split(',').map(str::trim).filter(|s| !s.is_empty()).map(|s| format!("{scope} {s}")).collect();
        out += "\n";
        out += &scoped.join(",\n");
        out += " ";
        out += body;
        rest = &rest[close + 1..];
    }
    out += rest;
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn highlights_known_languages() {
        let html = highlight("fn main() {}\n", "rust", "hl-").unwrap();
        assert!(html.contains("hl-"), "{html}");
        assert!(html.contains("language-rust"));
        assert!(highlight("x", "toml", "hl-").is_some());
        assert!(highlight("x", "ts", "hl-").is_some());
        assert!(highlight("x", "no-such-language", "hl-").is_none());
    }

    #[test]
    fn scopes_css() {
        let css = scope_css(".a, .b { color: red; }\n/* c */\n.c { x: y; }", "[data-theme=light]");
        assert!(css.contains("[data-theme=light] .a,\n[data-theme=light] .b {"), "{css}");
        assert!(css.contains("/* c */\n[data-theme=light] .c {"), "{css}");
        let media = scope_css(".a { x: y; }", "@media (prefers-color-scheme: light)");
        assert_eq!(media, "\n@media (prefers-color-scheme: light) {\n.a { x: y; }\n}\n");
    }

    #[test]
    fn makes_css() {
        let css = css("hl-", "Nord", Some("GitHub"), "[data-theme=light]").unwrap();
        assert!(css.contains(".hl-"));
        assert!(css.contains("[data-theme=light] .hl-"));
    }
}
